#!/usr/bin/env python3
"""Evasion: Obfuscator — code obfuscation for generated payloads."""
import ast
import random
import string
import base64

class Obfuscator:
    """Obfuscate Python source code."""

    def __init__(self):
        self.rename_map = {}
        self.junk_count = 0

    def _random_name(self, prefix="_"):
        return prefix + "".join(random.choices(string.ascii_lowercase + string.digits, k=random.randint(8, 16)))

    def obfuscate(self, source: str) -> str:
        """Apply obfuscation passes to source code."""
        # Pass 1: Rename local variables
        source = self._rename_variables(source)

        # Pass 2: Encrypt string literals
        source = self._encrypt_strings(source)

        # Pass 3: Insert junk code
        source = self._insert_junk(source)

        # Pass 4: Add anti-tampering header
        source = self._add_header(source)

        return source

    def _rename_variables(self, source: str) -> str:
        """Rename local variables to random names."""
        try:
            tree = ast.parse(source)
            renamed = {}

            for node in ast.walk(tree):
                if isinstance(node, ast.FunctionDef):
                    # Rename function arguments
                    for arg in node.args.args:
                        old = arg.arg
                        if old not in renamed and old not in ("self", "cls"):
                            new = self._random_name()
                            renamed[old] = new
                            arg.arg = new

                elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
                    old = node.id
                    if old not in renamed and not old.startswith("__"):
                        new = self._random_name()
                        renamed[old] = new
                        node.id = new

                elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
                    if node.id in renamed:
                        node.id = renamed[node.id]

            return ast.unparse(tree) if hasattr(ast, 'unparse') else source
        except:
            return source

    def _encrypt_strings(self, source: str) -> str:
        """Replace string literals with base64-encoded + XOR'd versions."""
        import re

        def replace_str(match):
            s = match.group(1)
            if len(s) < 3:
                return match.group(0)
            key = random.randint(1, 255)
            encoded = bytes(b ^ key for b in s.encode())
            b64 = base64.b64encode(encoded).decode()
            return f'_phantom_decode("{b64}", {key})'

        # Replace double-quoted strings (but not docstrings or f-strings)
        source = re.sub(r'(?<!f)"([^"]{3,})"', replace_str, source)
        source = re.sub(r"(?<!f)'([^']{3,})'", replace_str, source)

        # Add decoder function at the top
        decoder = '''
import base64 as _b
def _phantom_decode(_e, _k):
    return bytes(_b ^ _k for _b in _b.b64decode(_e)).decode()

'''
        return decoder + source

    def _insert_junk(self, source: str) -> str:
        """Insert junk code lines between real code."""
        lines = source.split("\n")
        new_lines = []

        for line in lines:
            new_lines.append(line)
            # 15% chance to insert junk after non-trivial lines
            if random.random() < 0.15 and line.strip() and not line.strip().startswith("#"):
                indent = len(line) - len(line.lstrip())
                junk_var = self._random_name("_j")
                junk_val = random.randint(0, 99999)
                new_lines.append(" " * indent + f"{junk_var} = {junk_val}")
                self.junk_count += 1

        return "\n".join(new_lines)

    def _add_header(self, source: str) -> str:
        """Add obfuscation header."""
        header = f'''# Auto-generated by AbsoluteRatlogger Obfuscator
# Junk code inserted: {self.junk_count}
# DO NOT MODIFY — regenerated from source template

'''
        return header + source


def obfuscate(source: str) -> str:
    """Convenience function to obfuscate source code."""
    obf = Obfuscator()
    return obf.obfuscate(source)
